SPELLING_RULES = """
ОРФОГРАФИЯ И ТЕРМИНЫ (обязательно соблюдать):
- уголь, угли — для нагрева (НЕ «угол»)
- Калауд — устройство, куда кладут уголь, ставится на чашку (Kaloud, Lotus и т.п.). НЕ путать с колпаком.
- Колпак — металлический купол сверху на чашку и калауд, накрывает всё, нужен для быстрого прогрева. НЕ путать с калаудом.
- забивка, табак, чаша, фанел, киллер, турка — термины кальяна
- «сдвинуть угли к краю», «добавить уголь» — правильно
Проверяй правописание: пользователь не должен путаться из-за опечаток."""


def build_mixes_prompt(params: dict, available_tobaccos: list[str]) -> str:
    has_tobaccos = bool(available_tobaccos and available_tobaccos != ["Black Nana", "Blue Horse", "Darkside Core"])

    tobacco_block = ""
    if has_tobaccos:
        tobacco_block = f"""
У пользователя есть эти табаки: {available_tobaccos}.
СТРОГОЕ ПРАВИЛО: используй ТОЛЬКО табаки из этого списка. Не придумывай и не подставляй другие названия.
Названия табаков в ответе должны ТОЧНО совпадать с названиями из списка — без изменений, без сокращений."""
    else:
        tobacco_block = """
У пользователя нет своих табаков. Предложи миксы из реальных, существующих табаков.
Используй ТОЛЬКО табаки от этих производителей: Darkside, MUSTHAVE, Spectrum, Daily Hookah, Element, Satyr, Sebero, Black Burn, Bonche, Hype, Severniy, Jent, Deus, Nash, Trofimoff's.
Указывай полное название: «Бренд Вкус» (например: «Darkside Hola», «MUSTHAVE Pinkman», «Element Земляника»).
НЕ ИСПОЛЬЗУЙ табаки других брендов. НЕ ВЫДУМЫВАЙ несуществующие вкусы."""

    strength_map = {"low": "лёгкий", "medium": "средний", "high": "крепкий"}
    strength = strength_map.get(params.get("strength", "medium"), "средний")

    profiles = params.get("profiles", [])
    profiles_text = ", ".join(profiles) if profiles else "любой"

    return f"""Ты — профессиональный кальянщик с 10-летним опытом. Сгенерируй ровно 3 микса для кальяна.
{SPELLING_RULES}

Параметры сетапа:
- Чаша: {params.get("bowl", "phunnel")}
- Угли: калауд / фольга — {params.get("heat_control", "kaloud")}
- Крепость: {strength}
- Вкусовые предпочтения: {profiles_text}
{tobacco_block}

ОБЯЗАТЕЛЬНО: каждый микс — от 2 до 4 табаков. Три микса должны быть РАЗНЫМИ:
- разное количество табаков (например: 2, 3 и 4, или 2, 3 и 3);
- разные пропорции и сочетания;
- разные названия и описания.
Название микса — креативное, короткое (2–3 слова).
Описание вкуса — ровно 4–6 слов, без общих фраз.

Верни ТОЛЬКО валидный JSON, без комментариев и markdown:
{{
  "mixes": [
    {{
      "id": "mix_1",
      "title": "Название микса",
      "tobaccos": ["Бренд Вкус 1", "Бренд Вкус 2"],
      "flavor": "Описание вкуса 4-6 слов"
    }},
    {{
      "id": "mix_2",
      "title": "Название микса",
      "tobaccos": ["Бренд Вкус 1", "Бренд Вкус 2", "Бренд Вкус 3"],
      "flavor": "Описание вкуса 4-6 слов"
    }},
    {{
      "id": "mix_3",
      "title": "Название микса",
      "tobaccos": ["Бренд Вкус 1", "Бренд Вкус 2", "Бренд Вкус 3", "Бренд Вкус 4"],
      "flavor": "Описание вкуса 4-6 слов"
    }}
  ],
  "clarify": []
}}"""


DIRECTION_HINTS = {
    "movie": "Миксы должны быть привычные, не навязчивые — чтобы не отвлекать от просмотра.",
    "relax": "Миксы средние или крепкие, возможно с необычным интересным вкусом — для расслабления.",
    "surprise": "Абсолютно любой микс — полная свобода выбора, рандомные сочетания.",
}


def build_quick_mixes_prompt(direction: str, no_tobacco: bool) -> str:
    """Промпт для быстрого совета по цели вечера: только direction + нет/есть табак, остальное не учитывается."""
    hint = DIRECTION_HINTS.get(direction, DIRECTION_HINTS["surprise"])
    if no_tobacco:
        tobacco_block = """
У пользователя нет своих табаков. Предложи миксы из реальных, существующих табаков.
Используй ТОЛЬКО табаки от этих производителей: Darkside, MUSTHAVE, Spectrum, Daily Hookah, Element, Satyr, Sebero, Black Burn, Bonche, Hype, Severniy, Jent, Deus, Nash, Trofimoff's.
Указывай полное название: «Бренд Вкус». НЕ ИСПОЛЬЗУЙ табаки других брендов. НЕ ВЫДУМЫВАЙ несуществующие вкусы."""
    else:
        tobacco_block = """
У пользователя есть свои табаки (список не указан в быстром запросе). Подбери миксы из популярных табаков тех же брендов: Darkside, MUSTHAVE, Spectrum, Element и т.д. Указывай полное название бренда и вкуса."""

    return f"""Ты — профессиональный кальянщик. Дай ровно 3 рандомных микса для кальяна — быстрый совет по цели вечера.
{SPELLING_RULES}

Цель вечера: {hint}
{tobacco_block}

Требования: каждый микс — от 2 до 4 табаков. Три микса должны быть РАЗНЫМИ. Название микса — короткое (2–3 слова). Описание вкуса — 4–6 слов.

Верни ТОЛЬКО валидный JSON, без комментариев и markdown:
{{
  "mixes": [
    {{ "id": "mix_1", "title": "...", "tobaccos": ["...", "..."], "flavor": "..." }},
    {{ "id": "mix_2", "title": "...", "tobaccos": ["...", "...", "..."], "flavor": "..." }},
    {{ "id": "mix_3", "title": "...", "tobaccos": ["...", "...", "...", "..."], "flavor": "..." }}
  ],
  "clarify": []
}}"""


def build_instruction_prompt(mix: dict, params: dict) -> str:
    coal_count = params.get("coal_count_start", 3)
    coal_size = params.get("coal_size", 25)
    has_cap = params.get("has_cap", True)

    heat_device = "калауд" if params.get("heat_control") == "kaloud" else "фольга"
    cap_note = (
        "Колпак есть (металлический купол сверху) — учти: быстрый прогрев, равномерный жар."
        if has_cap
        else "Колпака нет — учти: жар уходит сверху, прогрев медленнее."
    )

    return f"""Ты — профессиональный кальянщик. Составь подробную инструкцию для микса.
{SPELLING_RULES}

Микс: {mix.get("title", "")}
Табаки: {mix.get("tobaccos", [])}
Чаша: {params.get("bowl", "phunnel")}
Угли: {heat_device}, {coal_count} шт, {coal_size} мм
{cap_note}

Правила:
- Каждый пункт в packing, warmup, smoking, if_not_opened — 1–2 коротких предложения, только суть, без воды.
- Названия табаков в поле "tobaccos" должны ТОЧНО совпадать с переданными выше.
- Для КАЖДОГО табака из микса укажи процент. Проценты в сумме = 100.
- Пропорции должны быть разными (база, акцент, дополнение) — не 50/50 для двух табаков, не 33/33/33 для трёх.
- Шаги забивки — конкретные, практичные, 3–5 пунктов.
- Прогрев — с учётом колпака (металлический купол) и типа чаши. Время прогрева — около 8 минут.
- warmup_seconds — 480 (8 минут прогрева).
- Курение — как тянуть, паузы, когда усилить/ослабить жар.
- Если не раскрылся — конкретные действия (добавить уголь, сдвинуть, подождать).
- Пиши как опытный кальянщик.
- Уверенный тон.
- Без академических объяснений.
- Короткие строки.
- Можно добавить 1 короткое предупреждение по жару.

Верни ТОЛЬКО валидный JSON, без комментариев и markdown:
{{
  "tobaccos": [
    {{"name": "Точное название табака", "percent": 45}}
  ],
  "packing": ["шаг 1", "шаг 2", "шаг 3"],
  "warmup": ["старт: {coal_count} угля", "прогрев: ~8 минут", "первые тяги аккуратные"],
  "warmup_seconds": 480,
  "smoking": ["тип тяги", "паузы", "управление жаром"],
  "if_not_opened": ["действие 1", "действие 2"]
}}"""
